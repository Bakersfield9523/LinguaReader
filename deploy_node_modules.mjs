import fs from 'fs';
import path from 'path';

const SRC = 'C:/Users/18995/WorkBuddy/2026-06-13-18-49-16/kimi_book_platform_new/app/dist/node_modules';
const DST = 'C:/Users/18995/Desktop/LinguaReader/node_modules';

const LOCK_CODES = new Set(['EPIPE', 'EPERM', 'ETXTBSY', 'EBUSY', 'EMFILE', 'ENOTEMPTY', 'ENOENT']);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function robustCopy(src, dst, retries = 20) {
  try {
    const st = fs.lstatSync(src);
    if (st.isFile() && fs.existsSync(dst)) {
      const dstsz = fs.statSync(dst).size;
      if (dstsz === st.size && dstsz > 0) return;
    }
  } catch { /* ignore */ }
  for (let attempt = 0; attempt < retries; attempt++) {
    try {
      const st = fs.lstatSync(src);
      if (st.isSymbolicLink()) return;
      if (st.isDirectory()) {
        if (!fs.existsSync(dst)) fs.mkdirSync(dst, { recursive: true });
        for (const e of fs.readdirSync(src)) {
          await robustCopy(path.join(src, e), path.join(dst, e), retries);
        }
        return;
      }
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      fs.copyFileSync(src, dst);
      return;
    } catch (err) {
      const code = err && err.code ? err.code : '';
      if (attempt === retries - 1 || !LOCK_CODES.has(code)) {
        console.warn(`[deploy] WARN skip ${src}: ${code || err.message}`);
        return;
      }
      await sleep(400);
    }
  }
}

