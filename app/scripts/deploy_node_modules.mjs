// 叠加拷贝：不清空 DST，仅覆盖/新增。遇到锁(EBUxY/EPERM)重试，最终仍失败则跳过该文件。
function copyFileRetry(srcF, dstF, tries = 8) {
  for (let i = 0; i < tries; i++) {
    try {
      fs.mkdirSync(path.dirname(dstF), { recursive: true });
      fs.copyFileSync(srcF, dstF);
      return true;
    } catch (e) {
      if (i === tries - 1) {
        console.log("SKIP", dstF, "->", e.code || e.message);
        return false;
      }
      sleep(250);
    }
  }
  return false;
}

function walk(s, d) {
  const st = fs.statSync(s);
  if (st.isDirectory()) {
    if (!fs.existsSync(d)) fs.mkdirSync(d, { recursive: true });
    for (const e of fs.readdirSync(s)) walk(path.join(s, e), path.join(d, e));
  } else {
    copyFileRetry(s, d);
  }
}

